import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const srcDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'frontend', 'src', 'lib');
const outFile = join(srcDir, 'i18n-extras.ts');

const scratchFiles = readdirSync(srcDir)
  .filter((f) => /^i18n-scratch-.*\.json$/.test(f))
  .sort();

if (scratchFiles.length === 0) {
  console.error('No i18n-scratch-*.json files found in ' + srcDir);
  process.exit(1);
}

const merged = new Map();
const fileOrder = [];
let total = 0;

for (const file of scratchFiles) {
  const entries = JSON.parse(readFileSync(join(srcDir, file), 'utf8'));
  if (!Array.isArray(entries)) {
    console.error(`Bad scratch file ${file}: expected a JSON array`);
    process.exit(1);
  }
  fileOrder.push(file);
  for (const entry of entries) {
    const { section, key, en, hi, mr } = entry;
    if (!section || !key || !en || !hi || !mr) {
      console.error(`Bad entry in ${file}:`, entry);
      process.exit(1);
    }
    const id = `${section}.${key}`;
    if (merged.has(id)) {
      const prev = merged.get(id);
      const same = prev.en === en && prev.hi === hi && prev.mr === mr;
      if (!same) {
        console.error(
          `Duplicate key "${id}" with different text:\n` +
            `  ${prev.file}: "${prev.en}" / "${prev.hi}" / "${prev.mr}"\n` +
            `  ${file}:      "${en}" / "${hi}" / "${mr}"`,
        );
        process.exit(1);
      }
      continue;
    }
    merged.set(id, { section, key, en, hi, mr, file });
    total++;
  }
}

function buildDict(lang) {
  const sections = new Map();
  for (const entry of merged.values()) {
    if (!sections.has(entry.section)) sections.set(entry.section, {});
    sections.get(entry.section)[entry.key] = entry[lang];
  }
  return sections;
}

function emitConst(name, lang, sections) {
  const body = [...sections.entries()]
    .map(([section, keys]) => {
      const keyLines = Object.entries(keys)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
      return `  ${section}: {\n${keyLines.join(',\n')}\n  },`;
    })
    .join('\n');
  return `export const ${name}: Record<string, Record<string, string>> = {\n${body}\n};\n`;
}

const enSections = buildDict('en');
const hiSections = buildDict('hi');
const mrSections = buildDict('mr');

const header = `// GENERATED by scripts/build-i18n-extras.mjs — do not edit by hand.
// Merged from the agent-produced i18n-scratch-*.json files.
`;
const out =
  header +
  '\n' +
  emitConst('EXTRA_EN', 'en', enSections) +
  '\n' +
  emitConst('EXTRA_HI', 'hi', hiSections) +
  '\n' +
  emitConst('EXTRA_MR', 'mr', mrSections);

writeFileSync(outFile, out, 'utf8');
console.log(`Wrote ${outFile} with ${total} keys from ${fileOrder.length} scratch files`);
